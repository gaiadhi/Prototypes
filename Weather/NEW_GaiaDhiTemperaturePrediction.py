# Defining a function to extract NASA data from its API for its respective date, latitude and longitude
def extract_nasa(date, lat, lon):
  date = date.strftime('%Y%m%d')
  nasa_api_url = f'https://power.larc.nasa.gov/api/temporal/daily/point?start={date}&end={date}&latitude={lat}&longitude={lon}&community=ag&parameters=T2M_MIN%2CT2M_MAX%2CPRECTOTCORR&format=json&header=true&time-standard=lst'
  response = requests.get(nasa_api_url)

  #Getting the output from the API as a .json file
  if response.status_code == 200:
    with open("data.json", "w") as f:
      json.dump(response.json(), f)

  #Reading data from the saved .json file
  with open("data.json", "r") as f:
    data = json.load(f)

  #Converting the contents of the .json file into a dataframe
  nasa_df = pd.DataFrame(data["properties"]["parameter"])
  all_values = nasa_df.values.flatten().tolist() # Gives the temperature and rainfall output as a list

  #The output looks like this ['TMIN', 'TMAX', "Rainfall"]
  return all_values # Returning the resultant list

def create_dataframe_row(date, lat, lon, flag):
  # Create a dictionary with the date, latitude, longitude, and NASA value
  nasa_value = extract_nasa(date, lat, lon)

  # FLAG values help to determine if data is created to TMIN or TMAX
  if flag == 0: #TMIN dataframe is created for NASA values
    data = {'Date': date, 'Latitude': lat, 'Longitude': lon, 'NASA': nasa_value[0]}
  elif flag == 1: #TMAX dataframe is created for NASA values
    data = {'Date': date, 'Latitude': lat, 'Longitude': lon, 'NASA': nasa_value[1]}
  else:
    print("Invalid Input: Nasa data cannot be extracted")

  df = pd.DataFrame(data, index=[0])
  return df

