path1 = '/content/gdrive/MyDrive/GAIAData/80-20/TmaxData_2010_2014.xlsx'
train_data = pd.read_excel(path1)
train_data

# path2 = '/content/gdrive/MyDrive/GAIAData/80-20/TmaxData_2010_2014.xlsx'
# train_data_tmax = pd.read_excel(path2)
# train_data_tmax

path3 = '/content/gdrive/MyDrive/GAIAData/80-20/TMAX_Test_2010_2014.xlsx'
test_data = pd.read_excel(path3)
test_data

train_data['Month'] = pd.to_datetime(train_data['Date']).dt.month #Extracting the months from the date column to determine its season (TRAIN)
train_data

test_data['Month'] = pd.to_datetime(test_data['Date']).dt.month #Extracting the months from the date column to determine its season (TRAIN)
test_data

"""## **DATA PREPARATION**

### **TIME FIXED EFFECT - SEASONALITY**
### Mapping out specific months to correlate with its respective seasons.


---



### Since, we are considering data from Tamil Nadu, we are using 6 seasons - Winter: Dec, Jan, Feb; Pre-summer, Summer, Southwest monsoon, Autumn and Northeast monsoon
"""

season_mapping = {
    12: 'Winter',
    1: 'Winter',
    2: 'Winter',
    3: 'Pre-Summer',
    4: 'Pre-Summer',
    5: 'Summer',
    6: 'Summer',
    7: 'Southwest Monsoon',
    8: 'Southwest Monsoon',
    9: 'Autumn',
    10: 'Autumn',
    11: 'Northeast Monsoon'
}

train_data['season'] = train_data['Month'].map(season_mapping)
train_data

test_data['season'] = test_data['Month'].map(season_mapping)
test_data

"""### **ONE HOT ENCODING THE SEASONS**


---


### Converts the categorical season data column into boolean value suitable for one hot encoding
"""

one_hot_encoded = pd.get_dummies(train_data['season'])
train_encoded = pd.concat([train_data, one_hot_encoded], axis=1) # Concatenates the original dataframe with the encoded season columns (TRAIN)
train_encoded #Data after encoding (TRAIN)

one_hot_encoded = pd.get_dummies(test_data['season'])
test_encoded = pd.concat([test_data, one_hot_encoded], axis=1) # Concatenates the original dataframe with the encoded season columns (TRAIN)
test_encoded #Data after encoding (TRAIN)

train_encoded = train_encoded.drop(['Month', 'season','Autumn', 'Date', 'Latitude', 'Longitude'], axis = 1)
train_encoded

test_encoded = test_encoded.drop(['Month', 'season','Autumn', 'Date', 'Latitude', 'Longitude'], axis = 1)
test_encoded

"""## **LINEAR REGRESSION**"""

# Defining the dependent/target and independent variables
y_train = train_encoded['IMD'] #Target variable for TRAINING SET
X_train = train_encoded.drop(['IMD'], axis = 1) #Independent variable for TRAINING SET
Y_test = test_encoded['IMD']
X_test = test_encoded.drop(['IMD'], axis = 1)

imputer = SimpleImputer(strategy="mean")
X_train = imputer.fit_transform(X_train)
X_test = imputer.transform(X_test)

model = LinearRegression()
model.fit(X_train, y_train)

y_pred = model.predict(X_test)

"""## **RESULTS**"""

#Print a dataframe showing the predicted value and the y_test vlaue in subsequent columns and a third column with the diference between them

df = pd.DataFrame({'Predicted Value': y_pred, 'Y_test': Y_test})
df['Difference'] = df['Predicted Value'] - df['Y_test']
print(df.to_string())

#Plot a graph showing y_pred in one colour with the points labeled on the graph and Y_test line in another colur with points on the graph. Can you show the value of the dots on the graph itself

