df = pd.DataFrame(IMD_Nasa)
df.dtypes

results = []

def adjust_imd_values(df):

    results = []  # Store the adjusted IMD values here
    for index, row in df.iterrows():
        # Extracting current row details

        lat, lon, current_imd, date = row['Latitude'], row['Longitude'], row['IMD'], row['Date']

        # Initialize target IMD to NaN (indicating no match found initially)
        target_imd = np.nan

        # Conditions based on latitude and longitude
        if 9.5 <= lat < 11.5:
          target_row = df[(df['Latitude'] == lat + 1) & (df['Date'] == date)]
        elif lat == 11.5 and 78.5 <= lon < 79.5:
          target_row = df[(df['Longitude'] == lon + 1) & (df['Date'] == date) & (df['Latitude'] == lat)]
        elif lat == 11.5 and lon == 79.5:
          target_row = df[(df['Longitude'] == lon - 1) & (df['Date'] == date) & (df['Latitude'] == lat)]

        if not target_row.empty:
            # If a matching row is found, take its IMD value for subtraction
            target_imd = target_row.iloc[0]['IMD']
        # Perform the subtraction if a matching row was found; otherwise, leave as NaN or current IMD
        result = current_imd - target_imd if not pd.isnull(target_imd) else np.nan
        results.append(result)

    # Add the results to the DataFrame as a new column
    df['error'] = results

# Apply the function to adjust IMD values
adjust_imd_values(df)
df['error'] = df['error'].abs()

# Display the modified DataFrame
df

error_column = df['error']

# Calculate error metrics
mae = np.mean(np.abs(error_column))
mse = np.mean(error_column**2)
rmse = np.sqrt(mse)
std_deviation = np.std(error_column)

# Print calculated error metrics
print("Mean Absolute Error (MAE):", mae)
print("Mean Squared Error (MSE):", mse)
print("Root Mean Squared Error (RMSE):", rmse)
print("Standard Deviation of Errors:", std_deviation)

