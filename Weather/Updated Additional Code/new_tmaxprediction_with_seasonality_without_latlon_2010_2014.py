train_encoded

"""## **ALTITUDE WITH LAT AND LON**"""

coordinates = train_encoded[['Latitude', 'Longitude']]

cluster_range = range(1, 15)

# Initialize list to store the inertias (within-cluster sum of squares)
inertias = []

# Calculate the inertia for each number of clusters
for n_clusters in cluster_range:
    kmeans = KMeans(n_clusters=n_clusters, random_state=42)
    kmeans.fit(coordinates)
    inertias.append(kmeans.inertia_)

# Plot the elbow graph
plt.figure(figsize=(10, 6))
plt.plot(cluster_range, inertias, '-o', color='blue')
plt.title('Elbow Method for Determining Optimal Number of Clusters')
plt.xlabel('Number of clusters')
plt.ylabel('Inertia')
plt.xticks(cluster_range)
plt.grid(True)
plt.show()

lowest_k = inertias.index(min(inertias)) + 1

# Function to apply KMeans clustering
def apply_kmeans(X, n_clusters):
    kmeans = KMeans(n_clusters=n_clusters, random_state=42)
    clusters = kmeans.fit_predict(X[['Latitude', 'Longitude']])
    X_new = X.copy()
    X_new['Cluster'] = clusters
    return pd.get_dummies(X_new, columns=['Cluster'])

data_after_kmeans = apply_kmeans(train_encoded, n_clusters = lowest_k)
data_after_kmeans

